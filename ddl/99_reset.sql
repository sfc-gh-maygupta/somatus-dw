USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_INGEST;
USE SCHEMA SOMATUS_DEMO.BRONZE;

-- Empty Bronze (also clears COPY load metadata for these tables)
TRUNCATE TABLE MEMBERS_RAW;
TRUNCATE TABLE CLAIMS_RAW;
TRUNCATE TABLE LABS_RAW;

-- Baseline Silver/Gold that do NOT reference the client's future columns, so Bronze
-- can evolve without breaking anything downstream (opt-in step is in 03_medallion.sql)
CREATE OR REPLACE DYNAMIC TABLE SOMATUS_DEMO.SILVER.MEMBERS_CLEAN
  TARGET_LAG='1 minute' WAREHOUSE=WH_TRANSFORM REFRESH_MODE=INCREMENTAL AS
SELECT MEMBER_ID, CLIENT_ID, DOB, GENDER, CKD_STAGE, STATE, FILE_NAME, LOADED_AT
FROM SOMATUS_DEMO.BRONZE.MEMBERS_RAW
WHERE MEMBER_ID IS NOT NULL AND DOB IS NOT NULL AND LENGTH(STATE) = 2
QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY LOADED_AT DESC) = 1;
CREATE OR REPLACE DYNAMIC TABLE SOMATUS_DEMO.SILVER.CLIENT_CLAIMS
  TARGET_LAG='1 minute' WAREHOUSE=WH_TRANSFORM REFRESH_MODE=INCREMENTAL AS
SELECT CLAIM_ID, MEMBER_ID, CLIENT_ID, TRY_TO_DATE(SERVICE_DATE) AS SERVICE_DATE, CPT_CODE,
       PAID_AMOUNT::NUMBER(12,2) AS PAID_AMOUNT, CLAIM_STATUS, FILE_NAME, LOADED_AT
FROM SOMATUS_DEMO.BRONZE.CLAIMS_RAW;
CREATE OR REPLACE DYNAMIC TABLE SOMATUS_DEMO.GOLD.CLIENT_CKD_SUMMARY
  TARGET_LAG='1 minute' WAREHOUSE=WH_TRANSFORM REFRESH_MODE=INCREMENTAL AS
SELECT CLIENT_ID, CKD_STAGE, COUNT(*) AS MEMBERS
FROM SOMATUS_DEMO.SILVER.MEMBERS_CLEAN GROUP BY 1, 2;

-- Now safe to remove the evolved columns so schema evolution can be shown again live
ALTER TABLE MEMBERS_RAW DROP COLUMN IF EXISTS DIALYSIS_MODALITY;
ALTER TABLE CLAIMS_RAW  DROP COLUMN IF EXISTS PLACE_OF_SERVICE;

-- Recreate pipes = wipe Snowpipe's 14-day file memory (same SQS ARN is kept)
CREATE OR REPLACE PIPE PIPE_MEMBERS AUTO_INGEST=TRUE AS
COPY INTO MEMBERS_RAW FROM @S3_CLIENT_DROP/members/
  FILE_FORMAT=(FORMAT_NAME=FF_CSV) MATCH_BY_COLUMN_NAME=CASE_INSENSITIVE
  INCLUDE_METADATA=(FILE_NAME=METADATA$FILENAME, LOADED_AT=METADATA$START_SCAN_TIME) ON_ERROR=CONTINUE;
CREATE OR REPLACE PIPE PIPE_CLAIMS AUTO_INGEST=TRUE AS
COPY INTO CLAIMS_RAW FROM @S3_CLIENT_DROP/claims/
  FILE_FORMAT=(FORMAT_NAME=FF_AVRO) MATCH_BY_COLUMN_NAME=CASE_INSENSITIVE
  INCLUDE_METADATA=(FILE_NAME=METADATA$FILENAME, LOADED_AT=METADATA$START_SCAN_TIME) ON_ERROR=CONTINUE;
CREATE OR REPLACE PIPE PIPE_LABS AUTO_INGEST=TRUE AS
COPY INTO LABS_RAW (RAW, FILE_NAME, LOADED_AT)
  FROM (SELECT $1, METADATA$FILENAME, METADATA$START_SCAN_TIME FROM @S3_CLIENT_DROP/labs/)
  FILE_FORMAT=(FORMAT_NAME=FF_JSON) ON_ERROR=CONTINUE;

-- Stream + merge target

-- Orchestration state
UPDATE SOMATUS_DEMO.OPS.DEMO_CONTROL SET VAL = 'FALSE' WHERE KEY = 'FAIL_VALIDATE';
TRUNCATE TABLE SOMATUS_DEMO.OPS.PIPELINE_LOG;

-- Concurrency demo
TRUNCATE TABLE SOMATUS_DEMO.BRONZE.CLAIMS_DAILY_LOAD;
ALTER WAREHOUSE WH_BI SET MAX_CLUSTER_COUNT = 4;

-- Dynamic tables pick up the empty Bronze on next refresh
ALTER DYNAMIC TABLE SOMATUS_DEMO.SILVER.MEMBERS_CLEAN REFRESH;
ALTER DYNAMIC TABLE SOMATUS_DEMO.SILVER.LAB_RESULTS REFRESH;
ALTER DYNAMIC TABLE SOMATUS_DEMO.SILVER.CLIENT_CLAIMS REFRESH;
CREATE OR REPLACE DYNAMIC TABLE SOMATUS_DEMO.GOLD.CLAIMS_PUBLISHED
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = WH_TRANSFORM REFRESH_MODE = INCREMENTAL INITIALIZE = ON_CREATE AS
SELECT CLAIM_ID, MEMBER_ID, CLIENT_ID, SERVICE_DATE, CPT_CODE, PAID_AMOUNT, CLAIM_STATUS, FILE_NAME, LOADED_AT
FROM SOMATUS_DEMO.SILVER.CLIENT_CLAIMS;   -- published claims: refreshed only by the Demo 4 pipeline

