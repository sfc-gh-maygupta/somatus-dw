-- ============================================================
-- SOMATUS DEMO · 00 SETUP
-- Database, schemas, workload-isolated warehouses, synthetic base data.
-- All data is synthetic. No PHI.
-- ============================================================
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS SOMATUS_DEMO;
CREATE SCHEMA IF NOT EXISTS SOMATUS_DEMO.BRONZE;
CREATE SCHEMA IF NOT EXISTS SOMATUS_DEMO.SILVER;
CREATE SCHEMA IF NOT EXISTS SOMATUS_DEMO.GOLD;
CREATE SCHEMA IF NOT EXISTS SOMATUS_DEMO.OPS;

-- One warehouse per workload = workload isolation (Kenny's #1 priority)
CREATE WAREHOUSE IF NOT EXISTS WH_INGEST     WAREHOUSE_SIZE='MEDIUM' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE COMMENT='Somatus demo: file loads';
CREATE WAREHOUSE IF NOT EXISTS WH_TRANSFORM  WAREHOUSE_SIZE='LARGE'  AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE COMMENT='Somatus demo: stored procs / dynamic tables';
CREATE WAREHOUSE IF NOT EXISTS WH_BI         WAREHOUSE_SIZE='SMALL'  MIN_CLUSTER_COUNT=1 MAX_CLUSTER_COUNT=4 SCALING_POLICY='STANDARD'
                                             AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE COMMENT='Somatus demo: Power BI (multi-cluster)';
-- Deliberately undersized single warehouse to recreate the "everything in one Synapse pool" pain
CREATE WAREHOUSE IF NOT EXISTS WH_SHARED_SYNAPSE_SIM WAREHOUSE_SIZE='XSMALL' MAX_CONCURRENCY_LEVEL=4
                                             AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE COMMENT='Somatus demo: simulated shared pool';

-- Tags for cost attribution (demo 6)
CREATE TAG IF NOT EXISTS SOMATUS_DEMO.OPS.WORKLOAD COMMENT='ingest | transform | bi';
CREATE TAG IF NOT EXISTS SOMATUS_DEMO.OPS.CLIENT   COMMENT='client that owns the data';
ALTER WAREHOUSE WH_INGEST    SET TAG SOMATUS_DEMO.OPS.WORKLOAD='ingest';
ALTER WAREHOUSE WH_TRANSFORM SET TAG SOMATUS_DEMO.OPS.WORKLOAD='transform';
ALTER WAREHOUSE WH_BI        SET TAG SOMATUS_DEMO.OPS.WORKLOAD='bi';

-- ---------- Synthetic base data (built with an XL for speed, then resized) ----------
ALTER WAREHOUSE WH_TRANSFORM SET WAREHOUSE_SIZE='XLARGE';
USE WAREHOUSE WH_TRANSFORM;
USE SCHEMA SOMATUS_DEMO.SILVER;

CREATE OR REPLACE TABLE CLIENTS (CLIENT_ID STRING, CLIENT_NAME STRING) AS
SELECT * FROM VALUES ('HUMANA_DEMO','Humana (demo)'),('AETNA_DEMO','Aetna (demo)'),('CIGNA_DEMO','Cigna (demo)');

-- 2M members
CREATE OR REPLACE TABLE MEMBERS AS
SELECT 'M' || LPAD(SEQ4()::STRING, 8, '0')                              AS MEMBER_ID,
       DECODE(UNIFORM(1,3,RANDOM()),1,'HUMANA_DEMO',2,'AETNA_DEMO','CIGNA_DEMO') AS CLIENT_ID,
       DATEADD(day, -UNIFORM(18000, 32000, RANDOM()), CURRENT_DATE())      AS DOB,
       DECODE(UNIFORM(1,2,RANDOM()),1,'F','M')                           AS GENDER,
       'CKD' || UNIFORM(3,5,RANDOM())                                    AS CKD_STAGE,
       ARRAY_CONSTRUCT('VA','MD','DC','TX','FL','NY')[UNIFORM(0,5,RANDOM())]::STRING AS STATE
FROM TABLE(GENERATOR(ROWCOUNT => 2000000));

-- 100M claims (the heavy table for the stored-proc / BI concurrency demo)
CREATE OR REPLACE TABLE CLAIMS AS
SELECT 'C' || LPAD(SEQ8()::STRING, 11, '0')                              AS CLAIM_ID,
       'M' || LPAD(UNIFORM(0, 1999999, RANDOM())::STRING, 8, '0')        AS MEMBER_ID,
       DATEADD(day, -UNIFORM(0, 1095, RANDOM()), CURRENT_DATE())         AS SERVICE_DATE,
       ARRAY_CONSTRUCT('90935','90937','90945','90999','99214','80053','82565')[UNIFORM(0,6,RANDOM())]::STRING AS CPT_CODE,
       ROUND(UNIFORM(50, 9000, RANDOM()) + UNIFORM(0,99,RANDOM())/100, 2) AS PAID_AMOUNT,
       DECODE(UNIFORM(1,10,RANDOM()),1,'DENIED','PAID')                  AS CLAIM_STATUS
FROM TABLE(GENERATOR(ROWCOUNT => 100000000));

ALTER WAREHOUSE WH_TRANSFORM SET WAREHOUSE_SIZE='LARGE';
ALTER WAREHOUSE WH_TRANSFORM SUSPEND;
