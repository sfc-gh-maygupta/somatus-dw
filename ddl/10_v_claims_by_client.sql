CREATE OR REPLACE VIEW SOMATUS_DEMO.GOLD.V_CLAIMS_BY_CLIENT AS
SELECT CLIENT_ID,
       COUNT(*)                                          AS CLAIMS,
       SUM(IFF(CLAIM_STATUS = 'PAID', PAID_AMOUNT, 0))   AS TOTAL_PAID,
       ROUND(100 * AVG(IFF(CLAIM_STATUS = 'DENIED', 1, 0)), 1) AS DENIAL_RATE_PCT
FROM SOMATUS_DEMO.GOLD.CLAIMS_PUBLISHED
GROUP BY CLIENT_ID;
